// Export deployed addresses + ABIs into @amanah/shared.
//
// Reads:  packages/contracts/deployments/<chainId>.json   (labeled address ledger, script-emitted)
//         packages/contracts/out/<C>.sol/<C>.json          (forge build artifacts, .abi)
// Writes: packages/shared/src/addresses.ts                 (ADDRESSES, typed by ContractAddressKey)
//         packages/shared/src/abis/<C>.ts                  (one `export const <C>Abi = [...] as const`)
//         packages/shared/src/abis/index.ts                (barrel: re-exports + ABIS object)
//
// Zero runtime deps on purpose: this only does file IO + string templating. The real type
// safety gate is `tsc` in the next pipeline stage (pnpm --filter @amanah/shared build).

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const CHAIN_ID = 84532;

const scriptDir = dirname(fileURLToPath(import.meta.url));
const contractsDir = join(scriptDir, "..");
const outDir = join(contractsDir, "out");
const ledgerPath = join(contractsDir, "deployments", `${CHAIN_ID}.json`);
const sharedSrc = join(contractsDir, "..", "shared", "src");
const abisDir = join(sharedSrc, "abis");

const BANNER = "// AUTO-GENERATED by packages/contracts/script/export-shared.mjs — DO NOT EDIT.\n";

// Address labels, in the order they appear in the generated file (deterministic → clean diffs).
const ADDRESS_KEYS = [
  "mUSDC",
  "mXSGD",
  "mIDRX",
  "MockSwap",
  "CharityPool",
  "MockYieldVault",
  "MockHalalVault",
  "ReleaseController",
  "PayoutRouter",
];

// Contracts whose ABIs we export (one MockStablecoin ABI covers all three token addresses).
// Each lives in out/<name>.sol/<name>.json.
const ABI_CONTRACTS = [
  "CharityPool",
  "PayoutRouter",
  "ReleaseController",
  "MockYieldVault",
  "MockHalalVault",
  "MockSwap",
  "MockStablecoin",
];

function fail(msg) {
  console.error(`export-shared: ${msg}`);
  process.exit(1);
}

// --- addresses ---------------------------------------------------------------
const ledger = JSON.parse(readFileSync(ledgerPath, "utf8"));
for (const key of ADDRESS_KEYS) {
  const value = ledger[key];
  if (!value) fail(`missing "${key}" in ${ledgerPath} — re-run the deploy`);
  // Validate BEFORE interpolating into generated .ts: the ledger is a committed,
  // human-editable file, so a crafted value could otherwise break out of the string
  // literal and inject arbitrary TypeScript that executes when a consumer imports it.
  if (!/^0x[0-9a-fA-F]{40}$/.test(value)) {
    fail(`invalid address for "${key}" in ${ledgerPath}: ${JSON.stringify(value)} — expected 0x + 40 hex`);
  }
}

const unionLines = ADDRESS_KEYS.map((k) => `  | "${k}"`).join("\n");
const addrLines = ADDRESS_KEYS.map((k) => `    ${k}: "${ledger[k]}",`).join("\n");

const addressesTs =
  BANNER +
  `import { CHAIN_ID } from "./chain.js";\n` +
  `import type { Address } from "./types.js";\n\n` +
  `export type ContractAddressKey =\n${unionLines};\n\n` +
  `export const ADDRESSES = {\n` +
  `  [CHAIN_ID]: {\n${addrLines}\n  },\n` +
  `} as const satisfies Record<number, Record<ContractAddressKey, Address>>;\n`;

writeFileSync(join(sharedSrc, "addresses.ts"), addressesTs);

// --- abis --------------------------------------------------------------------
for (const name of ABI_CONTRACTS) {
  const artifactPath = join(outDir, `${name}.sol`, `${name}.json`);
  let artifact;
  try {
    artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
  } catch {
    fail(`cannot read ${artifactPath} — run \`forge build\` first`);
  }
  if (!Array.isArray(artifact.abi)) fail(`no .abi array in ${artifactPath}`);
  const abiJson = JSON.stringify(artifact.abi, null, 2);
  const fileTs = BANNER + `export const ${name}Abi = ${abiJson} as const;\n`;
  writeFileSync(join(abisDir, `${name}.ts`), fileTs);
}

const importLines = ABI_CONTRACTS.map((n) => `import { ${n}Abi } from "./${n}.js";`).join("\n");
const reexportLines = ABI_CONTRACTS.map((n) => `  ${n}Abi,`).join("\n");
const abisObjLines = ABI_CONTRACTS.map((n) => `  ${n}: ${n}Abi,`).join("\n");

const indexTs =
  BANNER +
  `${importLines}\n\n` +
  `export {\n${reexportLines}\n};\n\n` +
  `export const ABIS = {\n${abisObjLines}\n} as const;\n`;

writeFileSync(join(abisDir, "index.ts"), indexTs);

console.log(
  `export-shared: wrote addresses.ts (${ADDRESS_KEYS.length} addrs) + abis/ (${ABI_CONTRACTS.length} contracts) for chain ${CHAIN_ID}`
);
